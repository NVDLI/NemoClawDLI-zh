#!/usr/bin/env python3
"""Build a security review design package from canonical public records."""
from __future__ import annotations

import argparse
import io
import sys
import zipfile
from pathlib import Path

for _path in (Path(__file__).resolve(), *Path(__file__).resolve().parents):
    if (_path / "scripts" / "_bootstrap.py").exists():
        sys.path.insert(0, str(_path / "scripts"))
        break
from _bootstrap import find_repo_root


ROOT = find_repo_root(Path(__file__).resolve())
OUTPUT = ROOT / "artifacts" / "security-review" / "security-review-design.md"
PACKAGE = ROOT / "artifacts" / "security-review" / "securing-agents-dli-course-security-review.zip"
DIAGRAM = ROOT / "docs" / "security-architecture.svg"
SOURCES = (
    ROOT / "docs" / "product-design.md",
    ROOT / "docs" / "security-design.md",
    ROOT / "docs" / "security-control-disposition.md",
    ROOT / "docs" / "release-test-plan.md",
)


def demote_body(markdown: str) -> tuple[str, str]:
    """Return the source title and body with headings nested one level deeper."""
    lines = markdown.rstrip().splitlines()
    if not lines or not lines[0].startswith("# "):
        raise ValueError("source must start with one level-one heading")
    title = lines[0][2:].strip()
    output: list[str] = []
    fence: str | None = None
    for line in lines[1:]:
        stripped = line.lstrip()
        if stripped.startswith(("```", "~~~")):
            marker = stripped[:3]
            fence = None if fence == marker else marker if fence is None else fence
            output.append(line)
            continue
        if fence is None and line.startswith("#"):
            hashes, separator, rest = line.partition(" ")
            if separator and set(hashes) == {"#"} and len(hashes) < 6:
                line = "#" + hashes + separator + rest
        output.append(line)
    return title, "\n".join(output).strip()


def render() -> str:
    parts = [
        "# Security review design for the DLI course Securing Agents with OpenShell and NemoClaw",
        "",
        "> Generated by `python3 scripts/build/build_security_review_package.py`. Do not edit this file directly.",
        "",
        "## Review submission",
        "",
        "- Use this file as the single supporting design document.",
        "- Use the separately packaged `security-architecture.svg` as the architecture diagram.",
        "- Enter program identifiers, reviewer records, scan details, and approval state in the review system; they are intentionally absent from this public-safe design.",
        "",
        "## Composition and authority",
        "",
        "This design preserves the complete text of the repository's four canonical review records. Product scope, data handling, privacy, and cryptography come from `product-design.md`; trust boundaries and security controls come from `security-design.md`; repository, host, provider, residual, and non-applicable requirements come from `security-control-disposition.md`; verification claims and evidence ownership come from `release-test-plan.md`. The separate diagram is generated from `security-architecture.json` and validated against implementation evidence.",
    ]
    for index, source in enumerate(SOURCES, 1):
        title, body = demote_body(source.read_text(encoding="utf-8"))
        parts.extend(("", f"## Part {index}: {title}", "", f"Canonical source: [`{source.name}`]({source.name})", "", body))
    return "\n".join(parts).rstrip() + "\n"


def package_bytes(document: str) -> bytes:
    """Return a deterministic ZIP with exactly the document and diagram."""
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, content in (
            ("security-review-design.md", document.encode("utf-8")),
            ("security-architecture.svg", DIAGRAM.read_bytes()),
        ):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, content)
    return output.getvalue()


def display(path: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(ROOT))
    except ValueError:
        return str(resolved)


def self_test() -> int:
    title, body = demote_body("# Example\n\n## Section\n\n```text\n## literal\n```\n")
    assert title == "Example"
    assert "### Section" in body
    assert "```text\n## literal\n```" in body
    assert all(path.is_file() for path in SOURCES)
    assert DIAGRAM.is_file()
    document = render()
    assert document.startswith(
        "# Security review design for the DLI course Securing Agents with OpenShell and NemoClaw\n"
    )
    assert "# NemoClaw security review design" not in document
    first = package_bytes(document)
    assert first == package_bytes(render())
    with zipfile.ZipFile(io.BytesIO(first)) as archive:
        assert archive.namelist() == ["security-review-design.md", "security-architecture.svg"]
        assert archive.testzip() is None
    print("security review package generator self-test: PASS")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    parser.add_argument(
        "--package",
        nargs="?",
        const=PACKAGE,
        type=Path,
        help=(
            "Also write a deterministic two-file ZIP "
            "(default: artifacts/security-review/securing-agents-dli-course-security-review.zip)."
        ),
    )
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    generated = render()
    if args.check:
        if not args.out.is_file() or args.out.read_text(encoding="utf-8") != generated:
            print(f"security review design is stale: run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("security review design: current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(generated, encoding="utf-8")
    print(f"wrote {display(args.out)}")
    if args.package:
        args.package.parent.mkdir(parents=True, exist_ok=True)
        args.package.write_bytes(package_bytes(generated))
        print(f"wrote {display(args.package)} (security-review-design.md + security-architecture.svg)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
